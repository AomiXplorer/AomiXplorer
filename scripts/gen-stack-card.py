#!/usr/bin/env python3
"""
Generate the animated Stack card for the AomiXplorer profile README.

Data source: GitHub REST /repos/{owner}/{repo}/languages, summed over the 12
public non-fork repositories, snapshot 2026-11-13. Nobody types the numbers by
hand: they come from that snapshot (see LANG_BYTES below) so the card can be
regenerated by re-running the aggregation and pasting the totals.

Outputs (assets/):
  stack-light.svg, stack-dark.svg               -> wide card
  stack-mobile-light.svg, stack-mobile-dark.svg -> narrow card

Animation is SMIL (not CSS transforms) because SMIL survives GitHub's image
proxy and works inside <img> in every current browser. Each bar grows from
zero, staggered; text fades in behind it. Without JS, without external assets.
"""

import os

# ---------------------------------------------------------------- real numbers
# bytes per language, GitHub Languages API, 12 public repos, 2026-11-13
LANG_BYTES = {
    "TypeScript": 2570892,
    "HTML": 352956,
    "CSS": 214286,
    "JavaScript": 372491,
    "Kotlin": 318491,
    "Python": 146106,
    "Shell": 778,
}
TOTAL_BYTES = sum(LANG_BYTES.values())

# building blocks? no: these are the display rows, HTML+CSS folded into one bar
ROWS = [
    ("TypeScript", LANG_BYTES["TypeScript"], ("#3178C6", None)),
    ("HTML/CSS", LANG_BYTES["HTML"] + LANG_BYTES["CSS"], (None, ("#E44D26", "#2965F1"))),
    ("JavaScript", LANG_BYTES["JavaScript"], ("#F7DF1E", None)),
    ("Kotlin", LANG_BYTES["Kotlin"], ("#7F52FF", None)),
    ("Python", LANG_BYTES["Python"], ("#3776AB", None)),
]
OTHER_BYTES = TOTAL_BYTES - sum(b for _, b, _ in ROWS)
PCT = [(n, 100.0 * b / TOTAL_BYTES, c) for n, b, c in ROWS]

REPO_COUNT = 12
TOTAL_MB = TOTAL_BYTES / 1_000_000

TOOLS = [
    ("Frontend", ["React", "Next.js", "Tailwind", "Vite", "Compose", "Zustand", "TanStack", "Dexie"]),
    ("Backend", ["Route handlers", "REST", "protobuf / InnerTube", "WebCodecs"]),
    ("Environment", ["Git", "Actions", "Linux Mint", "Bash", "Vercel", "pipx"]),
]

FONT = "-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif"

THEMES = {
    "light": dict(bg="#fcfbfe", border="#ebe4f2", text="#1f2328", muted="#6b7280",
                  track="#f1ecf7", faint="#8b8894"),
    "dark": dict(bg="#0d1117", border="#21262d", text="#e6edf3", muted="#8b949e",
                 track="#1c2128", faint="#8b949e"),
}

# ------------------------------------------------------------------ measuring
try:
    from PIL import ImageFont
    _REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
    _BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

    def width(s, size, bold=False):
        f = ImageFont.truetype(_BOLD if bold else _REG, max(6, round(size)))
        return f.getlength(s)
except Exception:  # pragma: no cover - fallback keeps the build working
    def width(s, size, bold=False):
        return len(s) * size * (0.58 if not bold else 0.62)


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# ------------------------------------------------------------------- helpers
def text(x, y, s, size, fill, anchor="start", weight=400, opacity=None,
         spacing=None, fade=None):
    a = f' text-anchor="{anchor}"' if anchor != "start" else ""
    w = f' font-weight="{weight}"' if weight != 400 else ""
    sp = f' letter-spacing="{spacing}"' if spacing else ""
    op = f' opacity="{opacity}"' if opacity is not None else ""
    anim = ""
    if fade is not None:
        d, dur = fade
        anim = (f'<animate attributeName="opacity" from="0" to="1" begin="{d}s" '
                f'dur="{dur}s" fill="freeze"/>')
    return (f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" fill="{fill}"{a}{w}{sp}'
            f'{op}>{esc(s)}{anim}</text>')


def grow(rect_open, target_w, begin, dur=0.9):
    """rect_open = attributes without width/closing, width animates 0 -> target."""
    return (f'{rect_open} width="0">'
            f'<animate attributeName="width" from="0" to="{target_w:.1f}" begin="{begin}s" '
            f'dur="{dur}s" fill="freeze" calcMode="spline" keyTimes="0;1" '
            f'keySplines="0.25 0.8 0.35 1"/></rect>')


def wrap(items, maxw, size, sep="  ·  "):
    lines, cur = [], ""
    for it in items:
        cand = it if not cur else cur + sep + it
        if cur and width(cand, size) > maxw:
            lines.append(cur)
            cur = it
        else:
            cur = cand
    if cur:
        lines.append(cur)
    return lines


def bar_fill(color):
    solid, grad = color
    return solid, grad


# ------------------------------------------------------------------ wide card
def wide(theme_name):
    t = THEMES[theme_name]
    W, pad = 880, 30
    label_x, track_x, track_w, bar_h = pad, 200, 528, 12
    pct_x = W - pad
    head_y = 46
    rows_y0, row_step = 86, 44
    parts = []

    parts.append(text(label_x, head_y, "LANGUAGES", 10.5, t["faint"], weight=600, spacing="2.2"))
    parts.append(text(pct_x, head_y, f"{TOTAL_MB:.0f} MB  ·  {REPO_COUNT} public repos",
                      12, t["muted"], anchor="end"))

    for i, (name, pct, color) in enumerate(PCT):
        cy = rows_y0 + i * row_step
        begin = 0.15 + i * 0.13
        solid, grad = color
        parts.append(f'<rect x="{track_x}" y="{cy - bar_h/2:.1f}" width="{track_w}" '
                     f'height="{bar_h}" rx="{bar_h/2}" fill="{t["track"]}"/>')
        open_attr = (f'<rect x="{track_x}" y="{cy - bar_h/2:.1f}" rx="{bar_h/2}" '
                     f'height="{bar_h}" fill="url(#{grad_id(theme_name, name)})"'
                     if grad else
                     f'<rect x="{track_x}" y="{cy - bar_h/2:.1f}" rx="{bar_h/2}" '
                     f'height="{bar_h}" fill="{solid}"')
        parts.append(grow(open_attr, max(8.0, pct / 100 * track_w), begin))
        parts.append(text(label_x, cy + 5.2, name, 15, t["text"], weight=500,
                          fade=(begin - 0.05, 0.5)))
        parts.append(text(pct_x, cy + 4.6, f"{pct:.1f}%", 13.5, t["muted"],
                          anchor="end", fade=(begin + 0.25, 0.5)))

    last_bar_cy = rows_y0 + (len(PCT) - 1) * row_step
    div_y = last_bar_cy + 26
    parts.append(f'<line x1="{pad}" y1="{div_y}" x2="{pct_x}" y2="{div_y}" '
                 f'stroke="{t["border"]}" stroke-width="1"/>')

    tools_head_y = div_y + 30
    parts.append(text(label_x, tools_head_y, "TOOLS", 10.5, t["faint"], weight=600, spacing="2.2"))

    y = tools_head_y + 26
    value_x = pad + 118
    maxw = pct_x - value_x
    for i, (label, items) in enumerate(TOOLS):
        begin = 0.8 + i * 0.1
        lines = wrap(items, maxw, 13.5)
        parts.append(text(label_x, y, label.upper(), 10.5, t["faint"], weight=600, spacing="1.6",
                          fade=(begin, 0.5)))
        for ln in lines:
            parts.append(text(value_x, y, ln, 13.5, t["muted"], fade=(begin, 0.5)))
            y += 19
        y += 11

    H = y - 11 + 14
    return t, W, H, parts


# ---------------------------------------------------------------- mobile card
def mobile(theme_name):
    t = THEMES[theme_name]
    W, pad = 400, 22
    inner = W - 2 * pad
    head_y = 42
    rows_y0, row_step = 76, 50
    bar_h = 9
    parts = []

    parts.append(text(pad, head_y, "LANGUAGES", 10, t["faint"], weight=600, spacing="2"))
    parts.append(text(W - pad, head_y, f"{TOTAL_MB:.0f} MB · {REPO_COUNT} repos", 11,
                      t["muted"], anchor="end"))

    for i, (name, pct, color) in enumerate(PCT):
        y = rows_y0 + i * row_step
        begin = 0.15 + i * 0.13
        solid, grad = color
        parts.append(text(pad, y, name, 14, t["text"], weight=500, fade=(begin - 0.05, 0.5)))
        parts.append(text(W - pad, y, f"{pct:.1f}%", 12.5, t["muted"], anchor="end",
                          fade=(begin + 0.25, 0.5)))
        by = y + 8
        parts.append(f'<rect x="{pad}" y="{by}" width="{inner}" height="{bar_h}" '
                     f'rx="{bar_h/2}" fill="{t["track"]}"/>')
        open_attr = (f'<rect x="{pad}" y="{by}" rx="{bar_h/2}" height="{bar_h}" '
                     f'fill="url(#{grad_id(theme_name, name)})"'
                     if grad else
                     f'<rect x="{pad}" y="{by}" rx="{bar_h/2}" height="{bar_h}" fill="{solid}"')
        parts.append(grow(open_attr, max(7.0, pct / 100 * inner), begin))

    last_y = rows_y0 + (len(PCT) - 1) * row_step + 8 + bar_h
    div_y = last_y + 26
    parts.append(f'<line x1="{pad}" y1="{div_y}" x2="{W - pad}" y2="{div_y}" '
                 f'stroke="{t["border"]}" stroke-width="1"/>')

    tools_head_y = div_y + 28
    parts.append(text(pad, tools_head_y, "TOOLS", 10, t["faint"], weight=600, spacing="2"))

    y = tools_head_y + 24
    for i, (label, items) in enumerate(TOOLS):
        begin = 0.8 + i * 0.1
        parts.append(text(pad, y, label.upper(), 9.5, t["faint"], weight=600, spacing="1.5",
                          fade=(begin, 0.5)))
        y += 17
        for ln in wrap(items, inner, 12, sep=" · "):
            parts.append(text(pad, y, ln, 12, t["muted"], fade=(begin, 0.5)))
            y += 15.5
        y += 12

    H = y - 12 + 16
    return t, W, H, parts


def grad_id(theme, name):
    return "g-" + name.lower().replace("/", "-").replace(" ", "")


def grads():
    out = []
    for theme in THEMES:
        out.append(f'<linearGradient id="{grad_id(theme, "HTML/CSS")}" x1="0" x2="1" y1="0" y2="0">'
                   f'<stop offset="0" stop-color="#E44D26"/>'
                   f'<stop offset="0.55" stop-color="#C33F6B"/>'
                   f'<stop offset="1" stop-color="#2965F1"/>'
                   f'</linearGradient>')
    return "".join(out)


def build(theme_name, kind):
    t, W, H, parts = wide(theme_name) if kind == "wide" else mobile(theme_name)
    alt = ("Stack: TypeScript 64.7 percent, HTML/CSS 14.3 percent, JavaScript 9.4 percent, "
           "Kotlin 8.0 percent, Python 3.7 percent of about four megabytes across twelve public "
           "repositories. Frontend React, Next.js, Tailwind, Vite, Compose, Zustand, TanStack, "
           "Dexie. Backend route handlers, REST, protobuf InnerTube, WebCodecs. Environment Git, "
           "Actions, Linux Mint, Bash, Vercel, pipx.")
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" font-family="{FONT}">
<title>Stack</title><desc>{esc(alt)}</desc>
<defs>
{grads()}
<clipPath id="clip"><rect x="0" y="0" width="{W}" height="{H}" rx="14"/></clipPath>
</defs>
<g clip-path="url(#clip)">
<rect x="0.5" y="0.5" width="{W-1}" height="{H-1}" rx="14" fill="{t["bg"]}" stroke="{t["border"]}"/>
{chr(10).join(parts)}
</g>
</svg>
'''


if __name__ == "__main__":
    out = "build"
    os.makedirs(out, exist_ok=True)
    for theme in THEMES:
        for kind in ("wide", "mobile"):
            svg = build(theme, kind)
            name = f"stack-{kind}-{theme}.svg" if kind == "mobile" else f"stack-{theme}.svg"
            with open(os.path.join(out, name), "w") as fh:
                fh.write(svg)
            print("wrote", name, len(svg), "bytes")
